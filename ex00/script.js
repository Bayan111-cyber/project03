const name = "Bayan";/* const تعني أن قيمة المتغير لا يمكن تغييرها لاحقًا.*/
let age = 23;/* let تعني أن قيمة المتغير يمكن تغييرها لاحقًا. */
let coding = true;/* let تعني أن قيمة المتغير يمكن تغييرها لاحقًا. */

console.log("Welcome, " + name + "!");/* console.log() تستخدم لطباعة المعلومات في وحدة التحكم. */
console.log("Age:", age);/* console.log() تستخدم لطباعة المعلومات في وحدة التحكم. */
console.log("Coding:", coding);/* console.log() تستخدم لطباعة المعلومات في وحدة التحكم. */

age = age + 1;/* تحديث قيمة المتغير age بزيادة 1. */

console.log("New age:", age);/* console.log() تستخدم لطباعة المعلومات في وحدة التحكم. */
console.log("Name type:", typeof name);/* typeof تستخدم لمعرفة نوع البيانات للمتغير. */
console.log("Age type:", typeof age);/* typeof تستخدم لمعرفة نوع البيانات للمتغير. */
console.log("Coding type:", typeof coding); /* typeof تستخدم لمعرفة نوع البيانات للمتغير. */